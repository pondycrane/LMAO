// Cardputer native client (ESP32-S3 + Cap LoRa-1262 SX1262, ESP-IDF).
//
// Native replacement for the MicroPython cardputer_client (PR1 = sensor node,
// send-only): boots RTReticulum with the onboard SX1262 LoRa interface,
// persists an identity in NVS, announces lmao/cardputer + lxmf/delivery on the
// LMAO mesh, learns the server's delivery identity from its periodic announce,
// and every INTERVAL sends a SensorReport (die temp always; DHT20 humidity
// when a Grove sensor is attached) as a send-only LXMF message to the server.
//
// PR2 = receive + chart: registers an inbound packet callback on the IN
// lxmf/delivery destination so RTReticulum delivers the server's OPPORTUNISTIC
// LXM reply (already RNS-decrypted) to on_server_packet, which verifies the
// sender's signature, decodes the LMAOEnvelope→TextMessage, lifts the "DATA"
// chart line, and the main loop renders it on the ST7789 panel.
