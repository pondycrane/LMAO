#!/usr/bin/env bash
# Build the RoboDog native firmware (Waveshare ESP32-S3 RLCD-4.2, LVGL family
# calendar client) with ESP-IDF via Docker.  Stages this repo's app into a
# fresh RTReticulum checkout (its components/rtreticulum wrapper compiles the
# RNS lib + ESP-IDF HAL), then builds for the ESP32-S3 target.
#
# Build-time injection (source tree never modified):
#   LMAO_DEST_HASH_HEX     server delivery hash (32 hex) — baked into the app
#   LMAO_NODE_IDENTITY_HEX 64-byte private-key hex (no-drift scheme): pin the
#                          same canonical identity the MicroPython client uses
#                          so the delivery hash never changes across
#                          re-flashes / NVS erases.
#   LMAO_INTERVAL_SECONDS  calendar sync interval (default 1800, min 60)
#   LMAO_CALENDAR_ID       calendar id to request (default "family")
#   LMAO_WIFI_SSID / LMAO_WIFI_PASS   WiFi credentials
#   LMAO_SERVER_HOST       RNS TCP server host (default 192.168.50.67)
#   LMAO_SERVER_PORT       RNS TCP server port (default 4246)
# These are written into a generated lmao_config.h in the *staged* copy (under
# .rtreticulum/firmware/robodog), mirroring cardputer_client/firmware/build.sh.
set -euo pipefail
# Locate the firmware source dir.  `bazel run //robodog_client:build_firmware`
# exports BUILD_WORKSPACE_DIRECTORY; a direct `./build.sh` from this dir uses $0.
if [ -n "${BUILD_WORKSPACE_DIRECTORY:-}" ]; then
    APP="$BUILD_WORKSPACE_DIRECTORY/robodog_client/firmware"
else
    APP="$(cd "$(dirname "$0")" && pwd)"
fi
PARENT="$(dirname "$APP")"
# Reuse the repo's single pinned RTReticulum checkout (the one Sprout's
# native-client build uses, at the WORKSPACE-pinned commit) so the RoboDog
# firmware compiles against the same rev — never a drifting fresh clone.
SPROUT_RTR="$(cd "$APP/../../smart_irrigation/native-client" 2>/dev/null && pwd)/.rtreticulum"
RTR="${RTRETICULUM_ROOT:-}"
if [ -z "$RTR" ] && [ -d "$SPROUT_RTR" ]; then
    RTR="$SPROUT_RTR"
fi
RTR="${RTR:-$PARENT/.rtreticulum}"
IDF_IMG="${IDF_IMG:-espressif/idf:v5.3.1}"

if [ ! -d "$RTR" ]; then
    echo "cloning RTReticulum -> $RTR"
    git clone -q --depth 1 https://github.com/0xSeren/RTReticulum "$RTR"
fi

DEST="$RTR/firmware/robodog"
mkdir -p "$DEST"
# Only remove our host-owned source dirs; the container (root) owns build/
# and ninja rebuilds deltas in place.
rm -rf "$DEST/main" "$DEST/components" 2>/dev/null || true
mkdir -p "$DEST/components"
cp -r "$APP/main" "$DEST/main"
# Shared firmware component (firmware_common/): the protocol core the native
# clients use (lma_encoder/lma_calendar/lxmf_send/path_find/lma_identity) +
# the RTReticulum wrapper. Single canonical copy — no per-tree duplication.
cp -r "$APP/../../firmware_common/lma_common" "$DEST/components/lma_common"
cp -r "$APP/../../firmware_common/rtreticulum" "$DEST/components/rtreticulum"
cp "$APP/CMakeLists.txt" "$APP/sdkconfig.defaults" "$APP/partitions.csv" "$DEST/"
echo "app staged in $DEST"

# Generate the build-time config header in the staged copy (never the source).
HDR="$DEST/main/lmao_config.h"
# Clamp the sync interval to >= 60 s (mirrors the MicroPython client's
# _min_interval floor for this client).
INTERVAL="${LMAO_INTERVAL_SECONDS:-1800}"
if [ "$INTERVAL" -lt 60 ]; then INTERVAL=60; fi
{
    echo "// Generated by robodog_client/firmware/build.sh — do not edit."
    echo "#pragma once"
    echo '#ifndef LMAO_DEST_HASH_HEX'
    if [ -n "${LMAO_DEST_HASH_HEX:-}" ]; then
        printf '#define LMAO_DEST_HASH_HEX "%s"\n' "$LMAO_DEST_HASH_HEX"
    else
        echo '#define LMAO_DEST_HASH_HEX ""'
    fi
    echo '#endif'
    echo '#ifndef LMAO_NODE_IDENTITY_HEX'
    if [ -n "${LMAO_NODE_IDENTITY_HEX:-}" ]; then
        printf '#define LMAO_NODE_IDENTITY_HEX "%s"\n' "$LMAO_NODE_IDENTITY_HEX"
    else
        echo '#define LMAO_NODE_IDENTITY_HEX ""'
    fi
    echo '#endif'
    echo '#ifndef LMAO_INTERVAL_SECONDS'
    echo "#define LMAO_INTERVAL_SECONDS ${INTERVAL}"
    echo '#endif'
    echo '#ifndef LMAO_CALENDAR_ID'
    printf '#define LMAO_CALENDAR_ID "%s"\n' "${LMAO_CALENDAR_ID:-family}"
    echo '#endif'
    echo '#ifndef LMAO_WIFI_SSID'
    printf '#define LMAO_WIFI_SSID "%s"\n' "${LMAO_WIFI_SSID:-}"
    echo '#endif'
    echo '#ifndef LMAO_WIFI_PASS'
    printf '#define LMAO_WIFI_PASS "%s"\n' "${LMAO_WIFI_PASS:-}"
    echo '#endif'
    echo '#ifndef LMAO_SERVER_HOST'
    printf '#define LMAO_SERVER_HOST "%s"\n' "${LMAO_SERVER_HOST:-192.168.50.67}"
    echo '#endif'
    echo '#ifndef LMAO_SERVER_PORT'
    echo "#define LMAO_SERVER_PORT ${LMAO_SERVER_PORT:-4246}"
    echo '#endif'
} > "$HDR"
echo "generated $HDR"

docker run --rm -v "$RTR:/repo" -w /repo/firmware/robodog -e IDF_TARGET=esp32s3 \
    "$IDF_IMG" bash -lc 'git config --global --add safe.directory /repo; idf.py set-target esp32s3 && idf.py build' || exit 1
echo "Built: $DEST/build/robodog_native.bin"
