// RoboDog native client (Waveshare ESP32-S3 RLCD-4.2, ESP-IDF + LVGL v9).
//
// Native replacement for the MicroPython robodog_client family-calendar
// viewer: boots LVGL on the ST7305 reflective LCD, connects over WiFi to the
// server's RNS TCP interface, learns the server's delivery identity from its
// announce, and every INTERVAL sends a CalendarRequest (LXMF, watermark
// delta-sync).  Replies are delta-merged into a persistent event list and
// rendered through the LVGL subject data-binding; the last raw bundle +
// watermark are cached in NVS so the display comes up with stale-but-useful
// data before the first sync.
