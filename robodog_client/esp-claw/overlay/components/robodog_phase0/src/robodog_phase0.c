/* Embedded corpus utterance ("what can you do", 16 kHz WAV), generated by
 * build_esp_claw.sh from robodog_client/voice/corpus/capabilities.wav so the
 * single corpus copy of record stays authoritative (DRY). Provides a real
 * request payload for the device->Whisper round-trip probe. */
#include "robodog_asr_sample.inc"

static const char *TAG = "robodog";

/* ── RD_SHOT capture publishing ──────────────────────────────────────────── */

#define RD_SHOT_MAX_BUF       (16384)
#define RD_SHOT_INTERVAL_US   (4000000ULL) /* 15000 B -> ~30 KB hex @115200 ~= 2.6 s */

static portMUX_TYPE s_rdshot_mux = portMUX_INITIALIZER_UNLOCKED;
static uint8_t *s_rdshot_frame;     /* retained copy of the last flushed frame */
static uint8_t *s_rdshot_dump;      /* private copy the publisher prints from */
static size_t s_rdshot_len;
static int s_rdshot_w, s_rdshot_h;
static volatile bool s_rdshot_force;
static volatile uint64_t s_rdshot_last_pub_us;
static TaskHandle_t s_rdshot_task;

void robodog_rdshot_capture_now(void);
/* Declared in the overlay boards/waveshare.../setup_device.c: the custom
 * panel's live 1-bpp frame memory (deterministic RD_SHOT fallback). */
uint8_t *robodog_board_display_frame(size_t *out_len, int *out_w, int *out_h);

static void rd_shot_dump(const uint8_t *buf, size_t len, int w, int h)
{
    char line[65];
    unsigned o = 0;
    printf("\nRD_SHOT_BEGIN bufsize=%d w=%d h=%d\n", (int)len, w, h);
    /* 32 hex bytes per line, matching the hermes/calendar frame format that
     * capture.py HEX_RE[^0-9a-fA-F]+ / fromhex() round-trips. */
    for (o = 0; o < len; o++) {
        unsigned i = o & 0x1f;
        line[i * 2] = "0123456789abcdef"[buf[o] >> 4];
        line[i * 2 + 1] = "0123456789abcdef"[buf[o] & 0xf];
        if (i == 0x1f) {
            line[64] = '\0';
            printf("%s\n", line);
        }
    }
    if (o & 0x1f) {
        printf("%.*s\n", (int)((o & 0x1f) * 2), line);
    }
    printf("RD_SHOT_END\n");
    fflush(stdout);
}

static void rd_shot_task(void *arg)
{
    (void)arg;
    for (;;) {
        /* Wake on a flush notification OR the 4 s capture interval, so a
         * static LVGL screen (no dirty-region flushes after the first
         * paint) keeps yielding a continuous RD_SHOT stream instead of
         * stalling until the next repaint. */
        ulTaskNotifyTake(pdTRUE, pdMS_TO_TICKS(RD_SHOT_INTERVAL_US / 1000));
        const uint64_t now = esp_timer_get_time();
        const bool due = s_rdshot_force ||
                         (now - s_rdshot_last_pub_us >= RD_SHOT_INTERVAL_US);
        if (!due) {
            continue;
        }
        const uint8_t *frame = s_rdshot_frame;
        size_t len = s_rdshot_len;
        if (frame == NULL || len == 0) {
            /* Deterministic fallback: the panel's live 1-bpp frame memory is
             * always valid (blank white on a fresh boot, current content after
             * any render), so a capture never has "no frame" even before the
             * first flush arrives. */
            size_t plen = 0;
            int pw = 0, ph = 0;
            uint8_t *pf = robodog_board_display_frame(&plen, &pw, &ph);
            if (pf == NULL || plen == 0) {
                s_rdshot_force = false;
                ESP_LOGW(TAG, "rdshot: no panel frame captured yet");
                continue;
            }
            frame = pf;
            len = plen < RD_SHOT_MAX_BUF ? plen : RD_SHOT_MAX_BUF;
        }
        memcpy(s_rdshot_dump, frame, len);
        rd_shot_dump(s_rdshot_dump, len, s_rdshot_w != 0 ? s_rdshot_w : 400,
                     s_rdshot_h != 0 ? s_rdshot_h : 300);
        s_rdshot_last_pub_us = esp_timer_get_time();
        s_rdshot_force = false;
    }
}

void robodog_rdshot_publish(const uint8_t *buf, size_t len, int w, int h)
{
    if (buf == NULL || len == 0 || s_rdshot_frame == NULL || s_rdshot_dump == NULL) {
        return;
    }
    if (len > RD_SHOT_MAX_BUF) {
        len = RD_SHOT_MAX_BUF;
    }
    /* Always retain the latest flushed frame (a flush is low-frequency: text /
     * boot renders only), so a force-publish right after a UI render reads the
     * NEW frame, never a stale one held inside the 4 s self-tick window. */
    portENTER_CRITICAL(&s_rdshot_mux);
    memcpy(s_rdshot_frame, buf, len);
    s_rdshot_len = len;
    s_rdshot_w = w;
    s_rdshot_h = h;
    portEXIT_CRITICAL(&s_rdshot_mux);
    /* Wake the publisher when forced or when the capture interval elapsed. */
    const uint64_t now = esp_timer_get_time();
    if (s_rdshot_force || (now - s_rdshot_last_pub_us >= RD_SHOT_INTERVAL_US)) {
        xTaskNotifyGive(s_rdshot_task);
    }
}

static int cmd_rdshot(int argc, char **argv)
{
    (void)argc;
    (void)argv;
    robodog_rdshot_capture_now();
    return 0;
}

/* Immediate publish (bypasses the 4 s self-tick): used by the UI after a
 * forced LVGL refresh so RD_SHOT right now reflects the freshly rendered
 * frame instead of the retained one. */
void robodog_rdshot_capture_now(void)
{
    s_rdshot_force = true;
    if (s_rdshot_task != NULL) {
        xTaskNotifyGive(s_rdshot_task);
    } else {
        ESP_LOGW(TAG, "rdshot: not initialised yet");
    }
}

/* ── rd_asr: device -> Whisper multipart round-trip ─────────────────────── */

static int cmd_rd_asr(int argc, char **argv)
{
    (void)argc;
    (void)argv;
    static const char boundary[] = "----RoboDogClaw";
    /* Multipart parts are built with snprintf (a C string-literal cannot be
     * concatenated with a `boundary` variable). */
    char header[384];
    const size_t head_len = (size_t)snprintf(
        header, sizeof(header),
        "--%s\r\n"
        "Content-Disposition: form-data; name=\"model\"\r\n\r\n"
        "%s\r\n"
        "--%s\r\n"
        "Content-Disposition: form-data; name=\"file\"; filename=\"asr_sample.wav\"\r\n"
        "Content-Type: audio/wav\r\n\r\n",
        boundary, CONFIG_ROBODOG_ASR_MODEL, boundary);
    char footer[80];
    const size_t foot_len = (size_t)snprintf(footer, sizeof(footer), "\r\n--%s--\r\n", boundary);

    const size_t body_len = head_len + sizeof(robodog_asr_sample_wav) + foot_len;

    char *body = heap_caps_malloc(body_len, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (body == NULL) {
        ESP_LOGE(TAG, "rd_asr: no memory for %u B multipart body", (unsigned)body_len);
        return 1;
    }
    memcpy(body, header, head_len);
    memcpy(body + head_len, robodog_asr_sample_wav, sizeof(robodog_asr_sample_wav));
    memcpy(body + head_len + sizeof(robodog_asr_sample_wav), footer, foot_len);

    robodog_http_rx_t rx;
    robodog_http_rx_init(&rx, CONFIG_ROBODOG_ASR_MAX_RESPONSE);
    if (rx.buf == NULL) {
        ESP_LOGE(TAG, "rd_asr: no memory for response buffer");
        heap_caps_free(body);
        return 1;
    }

    esp_http_client_config_t cfg = {
        .url = CONFIG_ROBODOG_ASR_URL,
        .method = HTTP_METHOD_POST,
        .timeout_ms = 60000,
        .event_handler = robodog_http_event_handler,
        .user_data = &rx,
        .buffer_size = 512,
    };
    esp_http_client_handle_t client = esp_http_client_init(&cfg);
    if (client == NULL) {
        ESP_LOGE(TAG, "rd_asr: http client init failed");
        robodog_http_rx_free(&rx);
        heap_caps_free(body);
        return 1;
    }
    char ctype[96];
    snprintf(ctype, sizeof(ctype), "multipart/form-data; boundary=%s", boundary);
    esp_http_client_set_header(client, "Content-Type", ctype);
    esp_http_client_set_post_field(client, body, body_len);
    const esp_err_t err = esp_http_client_perform(client);
    const int status = esp_http_client_get_status_code(client);
    esp_err_t post_err = esp_http_client_cleanup(client);
    (void)post_err;

    ESP_LOGI(TAG, "rd_asr: POST %s -> http=%d err=%s body=%u B",
             CONFIG_ROBODOG_ASR_URL, status, esp_err_to_name(err), (unsigned)rx.len);
    if (err == ESP_OK && status >= 200 && status < 300 && rx.len > 0) {
        cJSON *root = cJSON_Parse(rx.buf);
        /* cJSON_GetObjectItemCaseSensitive returns a cJSON item, not a string. */
        cJSON *text = root != NULL ? cJSON_GetObjectItemCaseSensitive(root, "text") : NULL;
        if (text != NULL && cJSON_IsString(text)) {
            ESP_LOGI(TAG, "rd_asr: text=\"%s\"", text->valuestring);
        } else {
            ESP_LOGW(TAG, "rd_asr: no text field in response: %s", rx.buf);
        }
        if (root != NULL) {
            cJSON_Delete(root);
        }
    } else {
        ESP_LOGE(TAG, "rd_asr: round-trip failed: %s", rx.buf[0] ? rx.buf : "(empty body)");
    }

    robodog_http_rx_free(&rx);
    heap_caps_free(body);
    return 0;
}

/* ── rd_tts: device -> Kokoro TTS round-trip ────────────────────────────── */

static int cmd_rd_tts(int argc, char **argv)
{
    (void)argc;
    (void)argv;
    char json[384];
    snprintf(json, sizeof(json),
             "{\"model\":\"%s\",\"input\":\"RoboDog claw phase zero TTS round trip.\",\"voice\":\"%s\"}",
             CONFIG_ROBODOG_TTS_MODEL, CONFIG_ROBODOG_TTS_VOICE);

    robodog_http_rx_t rx;
    robodog_http_rx_init(&rx, CONFIG_ROBODOG_TTS_MAX_RESPONSE);
    if (rx.buf == NULL) {
        ESP_LOGE(TAG, "rd_tts: no memory for response buffer");
        return 1;
    }
    esp_http_client_config_t cfg = {
        .url = CONFIG_ROBODOG_TTS_URL,
        .method = HTTP_METHOD_POST,
        .timeout_ms = 60000,
        .event_handler = robodog_http_event_handler,
        .user_data = &rx,
        .buffer_size = 512,
    };
    esp_http_client_handle_t client = esp_http_client_init(&cfg);
    if (client == NULL) {
        ESP_LOGE(TAG, "rd_tts: http client init failed");
        robodog_http_rx_free(&rx);
        return 1;
    }
    esp_http_client_set_header(client, "Content-Type", "application/json");
    esp_http_client_set_post_field(client, json, strlen(json));
    const esp_err_t err = esp_http_client_perform(client);
    const int status = esp_http_client_get_status_code(client);
    esp_http_client_cleanup(client);

    ESP_LOGI(TAG, "rd_tts: POST %s -> http=%d err=%s body=%u B",
             CONFIG_ROBODOG_TTS_URL, status, esp_err_to_name(err), (unsigned)rx.len);
    if (err == ESP_OK && status >= 200 && status < 300 && rx.len >= 4) {
        const bool riff = rx.buf[0] == 'R' && rx.buf[1] == 'I' &&
                          rx.buf[2] == 'F' && rx.buf[3] == 'F';
        ESP_LOGI(TAG, "rd_tts: got %u WAV bytes (starts RIFF: %s)",
                 (unsigned)rx.len, riff ? "yes" : "no");
    } else {
        ESP_LOGE(TAG, "rd_tts: round-trip failed: http=%d err=%s body='%.160s'",
                 status, esp_err_to_name(err), rx.buf != NULL ? rx.buf : "");
    }
    robodog_http_rx_free(&rx);
    return 0;
}

/* ── rd_chat: device -> agent -> LLM via the native chat-injection seam ─── */

static int cmd_rd_chat(int argc, char **argv)
{
    if (argc < 2 || argv[1][0] == '\0') {
        ESP_LOGE(TAG, "rd_chat: usage: rd_chat <user text...>");
        return 1;
    }
    char text[1024];
    text[0] = '\0';
    for (int i = 1; i < argc; i++) {
        if (i > 1) {
            strlcat(text, " ", sizeof(text));
        }
        strlcat(text, argv[i], sizeof(text));
    }

    /* The exact native seam the webim HTTP handler uses (and Phase 2 will
     * feed ASR text through): a per-turn independent agent run against the
     * NVS-configured LLM endpoint, blocking for the reply.  flags=0 keeps the
     * response queue so receive_root_for() can collect the reply. */
    /* Render the user transcript first (same role/timing as a user message
     * finalizing), then mark the agent as reasoning while the run is in
     * flight; the reply is appended when it finalizes. */
    robodog_ui_show_user(text);
    robodog_ui_set_agent_state("thinking");

    uint32_t request_id = 0;
    esp_err_t err = claw_agent_mgr_start_root_run_text(
        text, NULL, 0, CONFIG_ROBODOG_LLM_TIMEOUT_MS, &request_id);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "rd_chat: start_root_run_text failed: %s (agent/LLM not ready?)",
                 esp_err_to_name(err));
        robodog_ui_set_agent_state("error");
        return 1;
    }
    claw_core_response_t resp;
    memset(&resp, 0, sizeof(resp));
    err = claw_agent_mgr_receive_root_for(request_id, &resp,
                                          CONFIG_ROBODOG_LLM_TIMEOUT_MS + 30000);
    if (err == ESP_OK && resp.text != NULL) {
        ESP_LOGI(TAG, "rd_chat reply: %s", resp.text);
        robodog_ui_show_assistant(resp.text);
        /* Text-only probe (no playback): the assistant render no longer sets
         * the terminal state itself, so mark the turn done here. */
        robodog_ui_set_agent_state("idle");
    } else if (resp.error_message != NULL) {
        ESP_LOGE(TAG, "rd_chat: agent error (%s): %s", esp_err_to_name(err),
                 resp.error_message);
        robodog_ui_set_agent_state("error");
        return 1;
    } else {
        ESP_LOGE(TAG, "rd_chat: receive_root_for failed: %s", esp_err_to_name(err));
        robodog_ui_set_agent_state("error");
        return 1;
    }
    return 0;
}

/* ── registration ────────────────────────────────────────────────────────── */

static void robodog_register_commands(void)
{
    const esp_console_cmd_t cmds[] = {
        {.command = "rdshot",
         .help = "force an RD_SHOT capture frame over the console",
         .func = &cmd_rdshot},
        {.command = "rd_asr",
         .help = "device->Whisper round-trip: POST the embedded corpus WAV",
         .func = &cmd_rd_asr},
        {.command = "rd_tts",
         .help = "device->Kokoro round-trip: POST JSON, receive WAV",
         .func = &cmd_rd_tts},
        {.command = "rd_chat",
         .help = "device->agent->LLM round-trip via the native injection seam",
         .func = &cmd_rd_chat},
    };
    for (size_t i = 0; i < sizeof(cmds) / sizeof(cmds[0]); i++) {
        if (esp_console_cmd_register(&cmds[i]) != ESP_OK) {
            ESP_LOGW(TAG, "failed to register console command '%s'", cmds[i].command);
        }
    }
}

esp_err_t robodog_init(void)
{
    s_rdshot_frame = heap_caps_malloc(RD_SHOT_MAX_BUF, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    s_rdshot_dump = heap_caps_malloc(RD_SHOT_MAX_BUF, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (s_rdshot_frame == NULL || s_rdshot_dump == NULL) {
        ESP_LOGW(TAG, "RD_SHOT capture unavailable (no SPIRAM); probes still work");
        if (s_rdshot_frame != NULL) {
            heap_caps_free(s_rdshot_frame);
            s_rdshot_frame = NULL;
        }
        if (s_rdshot_dump != NULL) {
            heap_caps_free(s_rdshot_dump);
            s_rdshot_dump = NULL;
        }
    } else if (xTaskCreate(rd_shot_task, "rdshot", 4096, NULL, 3, &s_rdshot_task) != pdPASS) {
        ESP_LOGW(TAG, "RD_SHOT publisher task create failed");
    }

    robodog_register_commands();
    /* Phase 1: bring up the deterministic text-only UI (panel + LVGL). */
    (void)robodog_ui_start();
    /* Phase 2: the device-initiated voice loop (rd_listen trigger). */
    (void)robodog_voice_init();
    ESP_LOGI(TAG, "RoboDog Phase 1 overlay ready: rdshot / rd_asr / rd_tts / rd_chat + text UI");
    return ESP_OK;
}
