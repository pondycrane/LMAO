// Report the socket's ENV III sample to the LMAO server (see net_report.h).
//
// The socket is the room's sensor AND actuator: its SensorReport keeps the
// server's ENV_HISTORY[node_id] series alive, and /status carries the same
// reading for the controller's direct path.  Identity is pinned at build time
// (HF_NODE_IDENTITY_HEX) so the delivery hash never drifts and the contact
// book approval stays valid across reflashes.
