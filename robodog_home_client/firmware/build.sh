#!/usr/bin/env bash
# Build the RoboDog home client firmware (ESP32-S3 + RLCD-4.2) via the ESP-IDF
# Docker image, staged into the repo's pinned RTReticulum checkout.
#
#   bazel run //robodog_home_client:build_firmware
#
# Build-time injection (written into the STAGED copy's generated
# lmao_config.h — the source tree is never modified, and NO credentials are
# baked in):
#   RH_DEST_HASH_HEX        server lxmf/delivery hash (32 hex)
#   RH_NODE_IDENTITY_HEX    64-byte private-key hex: the device's pinned
#                           identity (lma_core/client_identity.py per-device
#                           store), so the delivery hash never drifts
#   RH_INTERVAL_SECONDS     report/refresh cadence (default 60)
#   RH_SERVER_HOST_DEFAULT  server LAN hostname (default tp4)
#   RH_SERVER_PORT_DEFAULT  server RNS TCP port (default 4246)
#   RH_DEVICE_NAME_DEFAULT  default device name (NVS still wins at runtime)
#
# WiFi credentials are NEVER compiled in: they are written to the NVS
# partition by flash.sh at flash time (see README).
set -euo pipefail

if [ -n "${BUILD_WORKSPACE_DIRECTORY:-}" ]; then
    APP="$BUILD_WORKSPACE_DIRECTORY/robodog_home_client/firmware"
    ROBODOG="$BUILD_WORKSPACE_DIRECTORY/robodog_client"
else
    APP="$(cd "$(dirname "$0")" && pwd)"
    ROBODOG="$(cd "$APP/../../robodog_client" && pwd)"
fi

# Reuse the repo's single pinned RTReticulum checkout (the one the Sprout /
# Cardputer builds use) so this firmware compiles against the same rev.
RTR="${RTRETICULUM_ROOT:-$(cd "$APP/../../smart_irrigation/native-client" 2>/dev/null && pwd)/.rtreticulum}"
if [ ! -d "$RTR" ]; then
    echo "cloning RTReticulum -> $RTR"
    git clone -q --depth 1 https://github.com/0xSeren/RTReticulum "$RTR"
fi

IDF_IMG="${IDF_IMG:-espressif/idf:v5.3.1}"

# u8g2 is fetched, not vendored: reuse robodog_client's stager so both board
# firmwares share the one pinned upstream copy.
"$ROBODOG/u8g2_prepare.sh" "$ROBODOG"

# RTReticulum must be the SAME pinned rev the Bazel host path uses (WORKSPACE
# @rtreticulum, dab4362) WITH rtreticulum_fixes.patch applied: unpatched RTR
# rejects the server's ratcheted announce ("invalid announce sig" in
# transport.cpp), so the board never learns the delivery destination. The
# marker grep makes re-application idempotent on a checkout that predates
# this fix.
RTRET_PATCH="$APP/../../smart_irrigation/native-client/rtreticulum_fixes.patch"
RTR_REV=dab4362cf3577e464e98e85b71abc5cb26185224
if [ ! -d "$RTR/.git" ]; then
    echo "cloning RTReticulum (pinned ${RTR_REV:0:7}) -> $RTR"
    rm -rf "$RTR"
    git init -q "$RTR"
    git -C "$RTR" remote add origin https://github.com/0xSeren/RTReticulum
    git -C "$RTR" fetch -q --depth 1 origin "$RTR_REV"
    git -C "$RTR" checkout -q FETCH_HEAD
fi
if ! grep -q "create_ratchet" "$RTR/include/rtreticulum/destination.h"; then
    echo "applying rtreticulum_fixes.patch -> $RTR"
    git -C "$RTR" apply "$RTRET_PATCH"
fi

DEST="$RTR/firmware/robodog_home"
mkdir -p "$DEST"
rm -rf "$DEST/main" "$DEST/components" 2>/dev/null || true
mkdir -p "$DEST/components"
cp -r "$APP/main" "$DEST/main"
# Shared protocol core (firmware_common/) + the RTReticulum wrapper, and the
# LMAO-owned u8g2 components (same panel driver as the calendar firmware).
cp -r "$APP/../../firmware_common/lma_common" "$DEST/components/lma_common"
cp -r "$APP/../../firmware_common/rtreticulum" "$DEST/components/rtreticulum"
cp -r "$APP/../../firmware_common/tcp_interface" "$DEST/components/tcp_interface"
cp -r "$ROBODOG/components/u8g2" "$DEST/components/u8g2"
cp -r "$ROBODOG/components/u8g2_st7305" "$DEST/components/u8g2_st7305"
cp "$APP/CMakeLists.txt" "$APP/sdkconfig.defaults" "$APP/partitions.csv" "$DEST/"
echo "app staged in $DEST"

HDR="$DEST/main/lmao_config.h"
{
    echo "// Generated by robodog_home_client/firmware/build.sh — do not edit."
    echo "#pragma once"
    echo "#ifndef RH_DEST_HASH_HEX"
    if [ -n "${RH_DEST_HASH_HEX:-}" ]; then
        printf '#define RH_DEST_HASH_HEX "%s"\n' "$RH_DEST_HASH_HEX"
    else
        echo '#define RH_DEST_HASH_HEX ""'
    fi
    echo '#endif'
    echo '#ifndef RH_NODE_IDENTITY_HEX'
    if [ -n "${RH_NODE_IDENTITY_HEX:-}" ]; then
        printf '#define RH_NODE_IDENTITY_HEX "%s"\n' "$RH_NODE_IDENTITY_HEX"
    else
        echo '#define RH_NODE_IDENTITY_HEX ""'
    fi
    echo '#endif'
    echo '#ifndef RH_INTERVAL_SECONDS'
    echo "#define RH_INTERVAL_SECONDS ${RH_INTERVAL_SECONDS:-60}"
    echo '#endif'
    echo '#ifndef RH_SERVER_HOST_DEFAULT'
    printf '#define RH_SERVER_HOST_DEFAULT "%s"\n' "${RH_SERVER_HOST:-tp4}"
    echo '#endif'
    echo '#ifndef RH_SERVER_PORT_DEFAULT'
    echo "#define RH_SERVER_PORT_DEFAULT ${RH_SERVER_PORT:-4246}"
    echo '#endif'
    echo '#ifndef RH_DEVICE_NAME_DEFAULT'
    printf '#define RH_DEVICE_NAME_DEFAULT "%s"\n' "${RH_DEVICE_NAME:-}"
    echo '#endif'
} > "$HDR"
echo "generated $HDR"

docker run --rm -v "$RTR:/repo" -w /repo/firmware/robodog_home -e IDF_TARGET=esp32s3 \
    "$IDF_IMG" bash -lc 'git config --global --add safe.directory /repo; idf.py set-target esp32s3 && idf.py build' || exit 1
echo "Built: $DEST/build/robodog_home_native.bin"
